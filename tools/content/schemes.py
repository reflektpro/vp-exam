done = {}

def save(name, s):
    svg = s.svg(); assert len(svg) < 12000, (name, len(svg)); done[name] = len(svg)
    open(os.path.join(OUT, name + '.svg'), 'w').write(svg + '\n')

def T(s, x, y, t, size=15, anchor='middle', fill='#222', bold=False):
    for i, ln in enumerate(t.split('\n')): s.text(x, y + i * round(size * 1.25), ln, size, anchor, fill, bold)

def dim(s, x1, y1, x2, y2, label, col=BLUE, off=0, size=15, lx=None, ly=None, anchor='middle'):
    """Размерная линия с засечками."""
    s.line(x1, y1, x2, y2, col, 2)
    a = math.atan2(y2 - y1, x2 - x1); nx, ny = -math.sin(a) * 7, math.cos(a) * 7
    for (x, y) in ((x1, y1), (x2, y2)): s.line(round(x - nx, 1), round(y - ny, 1), round(x + nx, 1), round(y + ny, 1), col, 2)
    if label: T(s, lx if lx is not None else (x1 + x2) / 2, ly if ly is not None else (y1 + y2) / 2 - 8, label, size, anchor, col, True)

def ok(s, x, y, r=11):
    s.add(f'<circle cx="{x}" cy="{y}" r="{r}" fill="{GREEN}"/>'); s.path(f'M{x-5} {y} L{x-1} {y+4} L{x+6} {y-5}', '#fff', 3)
def no(s, x, y, r=11):
    s.add(f'<circle cx="{x}" cy="{y}" r="{r}" fill="{RED}"/>'); s.path(f'M{x-5} {y-5} L{x+5} {y+5} M{x+5} {y-5} L{x-5} {y+5}', '#fff', 3)
def mark(s, x, y, t, fill=VP, r=13, fs=12):
    """Кружок с буквами, без направления (начальник, ВП и т. п.)."""
    s.add(f'<circle cx="{x}" cy="{y}" r="{r}" fill="{fill}" stroke="#222" stroke-width="2"/>'); s.text(x, y + 4, t, fs, fill='#fff', bold=True)
def bld(s, x, y, w, h, t, fs=15):
    s.rect(x, y, w, h, BLD, '#7a6f55', 2, 3); T(s, x + w / 2, y + h / 2 + 5 - (t.count('\n') * fs * 0.62), t, fs, bold=True, fill='#4a4232')

