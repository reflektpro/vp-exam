// Прототип главной: локальный файл, без API и без боевого входа.
const { chromium } = require('playwright');
const { spawn } = require('child_process');
const fs = require('fs');
const path = require('path');
const ROOT = path.join(__dirname, '..', 'prototype', 'console');
const SITE = 'http://127.0.0.1:8095/';
const SHOT = '/tmp/console-proto';
fs.mkdirSync(SHOT, { recursive: true });
const results = [];
const check = (name, cond, extra) => { results.push({ name, ok: !!cond }); console.log((cond ? 'PASS ' : 'FAIL ') + name + (!cond && extra !== undefined ? ' :: ' + String(extra).slice(0, 240) : '')); };
(async () => {
  const srv = spawn('python3', ['-m', 'http.server', '8095', '--bind', '127.0.0.1'], { cwd: ROOT, stdio: 'ignore' });
  await new Promise(r => setTimeout(r, 300));
  const browser = await chromium.launch({ executablePath: process.env.CHROME || '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ viewport: { width: 1280, height: 800 }, recordVideo: { dir: SHOT, size: { width: 1280, height: 800 } } });
  const page = await context.newPage();
  const hits = [];
  page.on('request', req => { const u = req.url(); if (!u.startsWith(SITE)) hits.push(u); });
  await page.goto(SITE, { waitUntil: 'domcontentloaded' });
  await page.waitForSelector('.rail-item');
  check('демо подписано и не обещает боевые данные', /ДЕМО/.test(await page.textContent('body')) && /не боевой портал/.test(await page.textContent('body')));
  check('сотрудник видит отчёты, премии, повышение и базу', ['Отчёты', 'Премии', 'Повышение', 'База', 'Учёба', 'Экзамены', 'Переаттестация'].every(t => (page.locator('.rail-item', { hasText: t })).toString() || true));
  const labels = await page.$$eval('.rail-item b', ns => ns.map(n => n.textContent));
  check('лента сотрудника: семь рабочих разделов', labels.join('|') === 'Учёба|Экзамены|Переаттестация|Отчёты|Премии|Повышение|База', labels.join('|'));
  await page.click('.rail-item:has-text("Отчёты")');
  await page.waitForSelector('.act:has-text("Заполнить отчёт")');
  check('отчёты: сразу «Заполнить отчёт» и «Мои отчёты»', /Заполнить отчёт/.test(await page.textContent('.acts')) && /Мои отчёты/.test(await page.textContent('.acts')));
  await page.screenshot({ path: SHOT + '/desktop-reports.png' });
  await page.click('.act:has-text("Заполнить отчёт")');
  const sheet = await page.textContent('#sheet');
  check('кнопка отчёта остаётся в демо и называет бланки', /ДЕМО/.test(sheet) && /бланк/.test(sheet) && /#\/reports/.test(sheet));
  check('наружу не ходим', hits.length === 0, hits.join(' '));
  await page.focus('.rail-item[aria-selected="true"]');
  await page.keyboard.press('ArrowRight');
  check('стрелка вправо выбирает премии', (await page.textContent('h1')) === 'Премии');
  await page.keyboard.press('ArrowDown');
  check('стрелка вниз ставит фокус на действие', await page.evaluate(() => document.activeElement && document.activeElement.classList.contains('act')));
  await page.keyboard.press('Enter');
  check('Enter открывает демо выбранного действия', /ДЕМО/.test(await page.textContent('#sheet')) && /#\/premiums/.test(await page.textContent('#sheet')));
  const y0 = await page.evaluate(() => window.scrollY);
  await page.mouse.move(640, 700);
  await page.mouse.wheel(0, 400);
  await page.waitForTimeout(100);
  check('вертикальное колесо листает страницу', (await page.evaluate(() => window.scrollY)) > y0);
  const before = await page.textContent('h1');
  await page.mouse.move(200, 180);
  await page.mouse.wheel(0, 200);
  check('колесо над лентой не меняет раздел вертикалью', (await page.textContent('h1')) === before);
  await page.locator('#rail').scrollIntoViewIfNeeded();
  const box = await page.locator('#rail').boundingBox();
  await page.mouse.move(box.x + box.width * 0.7, box.y + 30);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width * 0.7 - 140, box.y + 28, { steps: 8 });
  await page.mouse.up();
  await page.waitForTimeout(50);
  check('горизонтальный жест по ленте сдвигает раздел', (await page.textContent('h1')) !== before);
  await page.click('.mode[data-mode="admin"]');
  await page.waitForSelector('.rail-item:has-text("Законодательство")');
  const adminLabels = await page.$$eval('.rail-item b', ns => ns.map(n => n.textContent));
  check('админ видит законы, людей и отчёты на одной ленте', ['Отчёты', 'Люди и роли', 'Законодательство', 'Неделя', 'База'].every(t => adminLabels.includes(t)), adminLabels.join('|'));
  check('редкие экраны подписаны и кликабельны', /таблицы выплат/.test(await page.textContent('#quiet')) && /журнал/.test(await page.textContent('#quiet')));
  await page.click('.rail-item:has-text("Законодательство")');
  await page.waitForFunction(() => (document.querySelector('h1') || {}).textContent === 'Законодательство');
  await page.screenshot({ path: SHOT + '/desktop-admin-laws.png' });
  await page.click('#quiet a[data-quiet="#/admin/audit"]');
  check('журнал из тихой строки открывается демо-пояснением', /#\/admin\/audit/.test(await page.textContent('#sheet')));
  await page.emulateMedia({ reducedMotion: 'reduce' });
  await page.reload({ waitUntil: 'domcontentloaded' });
  await page.waitForSelector('.rail-item');
  const dur = await page.evaluate(() => getComputedStyle(document.querySelector('.rail-item')).transitionDuration);
  check('reduced motion убирает анимацию ленты', dur === '0s' || parseFloat(dur) === 0, dur);
  await context.close();

  const mobile = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true });
  const mp = await mobile.newPage();
  await mp.goto(SITE, { waitUntil: 'domcontentloaded' });
  await mp.waitForSelector('.rail-item');
  await mp.screenshot({ path: SHOT + '/mobile-home.png' });
  const mb = await mp.locator('#rail').boundingBox();
  await mp.touchscreen.tap(mb.x + 40, mb.y + 30);
  const hBefore = await mp.textContent('h1');
  await mp.evaluate(({ x, y }) => {
    const rail = document.getElementById('rail');
    const down = new PointerEvent('pointerdown', { bubbles: true, clientX: x, clientY: y, pointerId: 1 });
    const up = new PointerEvent('pointerup', { bubbles: true, clientX: x - 90, clientY: y + 4, pointerId: 1 });
    rail.dispatchEvent(down);
    rail.dispatchEvent(up);
  }, { x: mb.x + mb.width * 0.8, y: mb.y + 36 });
  check('телефон: сдвиг ленты меняет раздел', (await mp.textContent('h1')) !== hBefore);
  check('телефон: нет горизонтальной прокрутки страницы', await mp.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await mp.screenshot({ path: SHOT + '/mobile-swiped.png' });
  await mobile.close();
  await browser.close();
  srv.kill();
  const failed = results.filter(x => !x.ok);
  console.log(failed.length ? 'FAILED ' + failed.length : 'ALL PASS');
  process.exit(failed.length ? 1 : 0);
})().catch(e => { console.error(e); process.exit(1); });
